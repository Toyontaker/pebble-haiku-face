function skeleton(t) { return t.replace(/[ぁ-んァ-ヶー]/g, ''); }

// 句に入っている表の季語を拾う。直近の句と同じ季語を候補から外すために使う。
// 長い語から見て、秋の水 を 秋 では拾わない。仮名の別表記と、漢字だけを比べる
// 照合（落ち葉＝落葉、山笑う＝山笑ふ）も見る。test/analyze.py の kigo_in と同じ手順
var WORDS = null;
function usedIn(texts) {
  if (!WORDS) {
    var rows = table(), seen = {};
    WORDS = [];
    for (var i = 0; i < rows.length; i++) {
      if (seen[rows[i].w]) continue;          // 初春・春駒は二季にまたがって二行ある
      seen[rows[i].w] = true;
      WORDS.push({ w: rows[i].w, s: skeleton(rows[i].w) });
    }
    WORDS.sort(function(a, b) { return b.w.length - a.w.length; });
  }
  var found = [];
  for (var t = 0; t < (texts || []).length; t++) {
    var h = texts[t], rest = h, sk = skeleton(h), mine = [];
    for (var j = 0; j < WORDS.length; j++) {
      var wd = WORDS[j].w;
      if (rest.indexOf(wd) < 0) continue;
      mine.push(wd);
      rest = rest.split(wd).join(new Array(wd.length + 1).join('　'));
    }
    for (var kana in ALIAS) {
      if (h.indexOf(kana) >= 0 && !has(mine, ALIAS[kana])) mine.push(ALIAS[kana]);
    }
    for (var k = 0; k < WORDS.length; k++) {
      var s = WORDS[k].s;
      if (s.length < 2 || sk.indexOf(s) < 0) continue;
      var inside = false;                     // 春の日 の中の 春日 は数えない
      for (var f = 0; f < mine.length; f++) {
        if (skeleton(mine[f]).indexOf(s) >= 0) { inside = true; break; }
      }
      if (!inside) mine.push(WORDS[k].w);
    }
    for (var m = 0; m < mine.length; m++) if (!has(found, mine[m])) found.push(mine[m]);
  }
  return found;
}

// 季重なりの照合。表（候補に出す語）だけでなく、きごさい歳時記の全季語（kigo_all.js）を見る。
// 候補に出さない動植物や暮らしの語（蝶・椿・汗・風鈴など）を、モデルは季語と気づかずに置くため
var ALL_WORDS = null;
// 照合から外す語。動詞や別の語の一部として季節と関わりなく出てくる（忍ぶ・茂る・踊る）、
// 色の名として使われる（橙）、ふだんの言葉として一年中使う（今年・去年）
var NOT_ALONE = { '忍': 1, '茂': 1, '踊': 1, '橙': 1, '今年': 1, '去年': 1 };

// 歴史的仮名遣いの語を、句で書かれやすい現代仮名遣いにも合わせる（山笑ふ → 山笑う）
function modern(w) {
  return w.replace(/ふ$/, 'う').replace(/ゐ/g, 'い').replace(/ゑ/g, 'え');
}

function allWords() {
  if (ALL_WORDS) return ALL_WORDS;
  var src = require('./kigo_all'), seen = {}, rows = table(), heads = [];
  // 表の語（候補に出す語）と全季語を合わせる。同じ語は一度だけ
  for (var r = 0; r < rows.length; r++) heads.push(rows[r].yomi ? [rows[r].w, rows[r].yomi] : [rows[r].w]);
  for (var s in src) {
    var items = src[s].split(' ');
    for (var i = 0; i < items.length; i++) heads.push(items[i].split('|'));
  }
  ALL_WORDS = [];
  for (var h = 0; h < heads.length; h++) {
    var f = heads[h], w = f[0];
    if (NOT_ALONE[w]) continue;
    var forms = [];
    for (var j = 0; j < f.length; j++) {
      if (!has(forms, f[j])) forms.push(f[j]);
      if (!has(forms, modern(f[j]))) forms.push(modern(f[j]));
    }
    for (var k = 0; k < forms.length; k++) {
      var t = forms[k];
      if (seen[t]) continue;                   // 読みごとの行や二季にまたがる語は一度だけ
      seen[t] = true;
      // 3字以下の仮名だけの語（はえ・だし・あら）は、ふつうの言葉の中に紛れるので見ない
      if (/^[ぁ-んァ-ヶー]{1,3}$/.test(t)) continue;
      ALL_WORDS.push({ w: w, t: t, s: skeleton(t) });
    }
  }
  for (var kana in ALIAS) ALL_WORDS.push({ w: ALIAS[kana], t: kana, s: '' });
  // 漢字の骨組みが長い語から当てる。秋の風 を 秋 より先に 秋風 として拾うため
  ALL_WORDS.sort(function(a, b) { return (b.s.length - a.s.length) || (b.t.length - a.t.length); });
  return ALL_WORDS;
}

// rest の中で、語 t がそのまま現れる位置。後ろに「色」が続くもの（桜色・藤色）は色の名なので数えない
function exactAt(rest, t) {
  for (var at = rest.indexOf(t); at >= 0; at = rest.indexOf(t, at + 1)) {
    if (rest.charAt(at + t.length) !== '色') return [at, at + t.length];
  }
  return null;
}

// 送り仮名や「の」の有無だけが違う書き方（落ち葉＝落葉、秋の風＝秋風）。
// 語の漢字が、間に仮名を2字まで挟んで同じ並びで現れる位置
function skeletonAt(rest, sk) {
  if (sk.length < 2) return null;
  for (var at = rest.indexOf(sk.charAt(0)); at >= 0; at = rest.indexOf(sk.charAt(0), at + 1)) {
    var p = at + 1, ok = true;
    for (var c = 1; c < sk.length && ok; c++) {
      var gap = 0;
      while (p < rest.length && /[ぁ-ん]/.test(rest.charAt(p)) && gap < 3) { p++; gap++; }
      if (gap > 2 || rest.charAt(p) !== sk.charAt(c)) ok = false;
      else p++;
    }
    if (ok && rest.charAt(p) !== '色') return [at, p];
  }
  return null;
}

// 句（行の配列）に入っている季語を、重なりなく拾って返す。二つ以上なら季重なり。
// 当たった所は伏せるので、秋の水 の中の 秋 や 水 は数えない。行をまたいでは当てない
function inHaiku(lines) {
  var rest = (lines || []).join('\n'), found = [], words = allWords();
  for (var j = 0; j < words.length; j++) {
    var wd = words[j], span = exactAt(rest, wd.t);
    if (!span) span = skeletonAt(rest, wd.s);
    if (!span) continue;
    if (!has(found, wd.w)) found.push(wd.w);
    rest = rest.slice(0, span[0]) + new Array(span[1] - span[0] + 1).join('　') + rest.slice(span[1]);
    j--;                                       // 同じ語がもう一度出ていれば、それも伏せる
  }
  return found;
}

// いまの天気で使ってよい条件の一覧を作る
// 直近3時間に雨か雪があったか。虹（上がった直後）や春泥（ぬかるみ）のように、
// いま降っていなくても、降ったことが景の前提になる語のために見る
function rainedRecently(w) {
  var h = w && w.hourly;
  if (!h || !h.precipitation || !h.precipitation.length) return false;
  for (var i = Math.max(0, h.precipitation.length - 4); i < h.precipitation.length; i++) {
    if (h.precipitation[i] > 0.05) return true;
  }
  return false;
}

function allowedGates(w) {
  var ok = [];
  if (!w) return ok;                       // 天気が不明なら天気に依る季語は使わない
  var code = w.code;
  var raining = (w.rain !== null && w.rain !== undefined && w.rain > 0.05) ||
                (code >= 51 && code <= 67) || (code >= 80 && code <= 82);
  var snowing = (code >= 71 && code <= 77) || code === 85 || code === 86;
  var foggy = code === 45 || code === 48;
  var clearSky = (code === 0 || code === 1) || (w.cloud !== null && w.cloud !== undefined && w.cloud <= 30);
  var cloudy = code === 3 || (w.cloud !== null && w.cloud !== undefined && w.cloud >= 50);
  var windy = w.wind !== null && w.wind !== undefined && w.wind >= 5;
  var freezing = w.temp !== null && w.temp !== undefined && w.temp <= 2;
  var chilly = w.temp !== null && w.temp !== undefined && w.temp <= 12;
  if (raining) ok.push('rain');
  if (snowing) ok.push('snow');
  if (foggy) ok.push('fog');
  if (clearSky) ok.push('clear');
  if (cloudy) ok.push('cloud');
  if (windy) ok.push('wind');
  if (freezing) ok.push('frost');
  if (chilly) ok.push('cold');
  if (rainedRecently(w)) ok.push('afterrain');
  if (code === 95 || code === 96 || code === 99) ok.push('thunder');
  return ok;
}

// その時に使える季語を選ぶ。
//   periods : ['初秋','三秋'] のような時期区分
//   period  : 'morning' などの時間帯（index.js の区分）
//   w       : 天気。null なら天気に依る季語を外す
//   max     : 返す語数
//   exclude : 外す語（直近の句で使った季語）。外すと一語も残らないときは外さない
// excludeCats: 外す分類（技法が物として描けない時候を外すときなど）
function pick(seasonKey, periods, timeOfDay, w, max, exclude, excludeCats) {
  var rows = table();
  var gates = allowedGates(w);
  var known = !!w;                             // 天気が取れているか。否定条件の判定に使う
  var sc = SEASON_CODE[seasonKey] || '';
  // 時間帯は朝・昼・夕・夜の4つに丸める
  var t = 'day';
  if (timeOfDay === 'deepnight' || timeOfDay === 'predawn' || timeOfDay === 'evening') t = 'night';
  else if (timeOfDay === 'dawn' || timeOfDay === 'sunrise' || timeOfDay === 'morning') t = 'morning';
  else if (timeOfDay === 'dusk' || timeOfDay === 'twilight') t = 'evening';

  var out = [];
  for (var i = 0; i < rows.length; i++) {
    var r = rows[i];
    if (r.season !== sc && !(sc === 'n' && r.season === 'n')) continue;
    if (excludeCats && has(excludeCats, r.cat)) continue;
    if (periods.length && !has(periods, r.period) && r.period) continue;
    if (r.time.length && !has(r.time, t)) continue;          // 時間帯が合わない
    var okGate = true;
    for (var g = 0; g < r.gate.length; g++) {
      var need = r.gate[g];
      if (need.charAt(0) === '!') {
        // 本意に反する事象。起きている間は外す（降っている間の「秋の水」など）。
        // 天気が分からないときは、起きていないと言い切れないので同じく外す
        if (!known || has(gates, need.substring(1))) { okGate = false; break; }
      } else if (!has(gates, need)) { okGate = false; break; }  // 起きていない事象の季語は外す
    }
    if (!okGate) continue;
    out.push(r);
  }
  if (exclude && exclude.length) {
    var fresh = [];
    for (var e = 0; e < out.length; e++) if (!has(exclude, out[e].w)) fresh.push(out[e]);
    if (fresh.length) out = fresh;
  }
  // 分類ごとに無作為に選ぶ。順番も毎回変える。
  // 固定の並びだと、モデルが先頭の語にばかり寄ってしまうため
  var byCat = {}, order = ['時候', '天文', '地理', '生活', '行事', '動物', '植物'], picked = [];
  for (var j = 0; j < out.length; j++) {
    (byCat[out[j].cat] = byCat[out[j].cat] || []).push(out[j]);
  }
  // 分類の巡回順も毎回変える。固定だと語数が分類数で割り切れないとき、
  // 端数がいつも先頭の分類（時候・天文・地理）に寄ってしまう
  shuffle(order);
  for (var c = 0; c < order.length; c++) {
    if (byCat[order[c]]) shuffle(byCat[order[c]]);
  }
  var round = 0, limit = max || 10;
  while (picked.length < limit && round < 40) {
    var added = false;
    for (var c2 = 0; c2 < order.length; c2++) {
      var list = byCat[order[c2]];
      if (list && list.length > round) {
        added = true;
        // 読みごとに行を分けた語は、どれか一つの読みだけを載せる
        var dup = false;
        for (var d = 0; d < picked.length; d++) if (picked[d].w === list[round].w) { dup = true; break; }
        if (dup) continue;
        picked.push(list[round]);
        if (picked.length >= limit) break;
      }
    }
    if (!added) break;
    round++;
  }
  return shuffle(picked);
}

function shuffle(a) {
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

// プロンプトに載せる一行。括弧に読み（読みで拍数が変わる語だけ）と語釈を添え、6拍以上は中七のみ可と印を付ける。
// plain を立てると語釈を外し、語と読みと拍数の印だけにする（{kigo_plain} 用）
function listText(seasonKey, periods, timeOfDay, w, max, plain, exclude, excludeCats) {
  var picked = pick(seasonKey, periods, timeOfDay, w, max, exclude, excludeCats);
  if (!picked.length) return null;
  var parts = [];
  for (var i = 0; i < picked.length; i++) {
    var r = picked[i], note = [];
    if (r.yomi) note.push(r.yomi);               // 読みで拍数が変わる語は、どの読みで数えたかを示す
    if (r.note && !plain) note.push(r.note);
    if (r.m >= 6) note.push(r.m + '拍・中七のみ');
    parts.push(note.length ? r.w + '（' + note.join('・') + '）' : r.w);
  }
  return parts.join('、');
}

